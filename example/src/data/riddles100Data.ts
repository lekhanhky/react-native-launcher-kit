// Helper tạo scramble letters chuẩn: chữ cái của từ + chữ nhiễu
function makeScramble(word: string, extra: string[] = ['A', 'M', 'O', 'N', 'T']): string[] {
  const letters = word.replace(/\s+/g, '').split('');
  const combined = [...letters, ...extra.slice(0, 3)];
  // Xáo trộn ngẫu nhiên xác định
  return combined.sort((a, b) => a.localeCompare(b));
}

